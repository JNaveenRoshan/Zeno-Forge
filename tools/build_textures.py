"""Shrink the Poly Haven 4K texture downloads to 1K and pack them into assets/textures.js
(data URIs, so index.html still works when opened by double-click).

Run:  python tools/build_textures.py [folder-with-the-zips]   (default: ~/Downloads)
Needs: Pillow, numpy. Sky: assets/textures/sky.jpg is produced separately (see tools/sky.html).
Source assets are CC0 from polyhaven.com.
"""
import base64, io, json, sys, zipfile
from pathlib import Path
import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else Path.home() / "Downloads"
OUT = ROOT / "assets/textures"
OUT.mkdir(parents=True, exist_ok=True)
SIZE = 1024
# key -> poly haven asset name
ASSETS = {
    "grass": "aerial_grass_rock",
    "asphalt": "asphalt_02",
    "floor": "concrete_floor_worn_001",
    "wall": "concrete_wall_008",
    "roof": "corrugated_iron_02",
}


def member(z, suffix):
    for n in z.namelist():
        if n.startswith("textures/") and n.endswith(suffix) and ".." not in n:
            return n
    raise FileNotFoundError(suffix)


def normal_from_height(h, strength):
    h = h.astype(np.float32)
    h = (h - h.min()) / max(1e-6, float(h.max() - h.min()))
    dx = (np.roll(h, -1, axis=1) - np.roll(h, 1, axis=1)) * strength
    dy = (np.roll(h, -1, axis=0) - np.roll(h, 1, axis=0)) * strength
    n = np.stack([-dx, dy, np.ones_like(h)], axis=-1)
    n /= np.linalg.norm(n, axis=-1, keepdims=True)
    return Image.fromarray(((n * 0.5 + 0.5) * 255).astype(np.uint8), "RGB")


packed = {}
for key, name in ASSETS.items():
    zp = SRC / f"{name}_4k.blend.zip"
    with zipfile.ZipFile(zp) as z:
        diff = Image.open(io.BytesIO(z.read(member(z, "_diff_4k.jpg")))).convert("RGB")
        disp = Image.open(io.BytesIO(z.read(member(z, "_disp_4k.png"))))
    diff = diff.resize((SIZE, SIZE), Image.LANCZOS)
    diff.save(OUT / f"{key}_diff.jpg", quality=85)
    h = np.array(disp.convert("I") if disp.mode not in ("L", "I", "I;16") else disp).astype(np.float32)
    hi = Image.fromarray(h).resize((SIZE, SIZE), Image.BILINEAR)
    nrm = normal_from_height(np.array(hi), strength=6.0)
    nrm.save(OUT / f"{key}_nor.jpg", quality=88)
    print(key, "ok")

for f in sorted(OUT.glob("*.jpg")):
    packed[f.stem] = "data:image/jpeg;base64," + base64.b64encode(f.read_bytes()).decode()

js = "// Generated by tools/build_textures.py from CC0 Poly Haven textures.\nwindow.ZENO_TEX=" + json.dumps(packed) + ";\n"
(ROOT / "assets/textures.js").write_text(js)
print("textures.js", len(js) // 1024, "KB:", ", ".join(sorted(packed)))
