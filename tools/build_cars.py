"""Shrink textures inside the simplified car GLBs and pack them into assets/cars.js (base64),
so index.html works when opened by double-click.

Pipeline (run from the project folder):
  1. npx gltfpack@0.21.0 -i assets/raw/cars2/<car>_src.glb -o assets/raw/cars2/<car>_hero.glb -si 0.2  -km -noq -mm
     npx gltfpack@0.21.0 -i assets/raw/cars2/<car>_src.glb -o assets/raw/cars2/<car>_lite.glb -si 0.04 -sa -km -noq -mm
  2. python tools/build_cars.py

Model credits (also shown in the app):
  ev  - "FREE Concept Car 011 - public domain (CC0)" by Unity Fan
  ice - "Lamborghini Revuelto" by Anatolian Studios, CC-BY-4.0
  suv - "2024 BMW M4 Coupe Competition" by KOElkastasbers, Sketchfab Standard licence
"""
import base64, io, json, struct
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "assets/raw/cars2"
# which versions to ship, and the max texture size for each
SHIP = {("ev", "hero"): 1024, ("ev", "lite"): 512, ("ice", "hero"): 1024, ("ice", "lite"): 512, ("suv", "lite"): 512}


def read_glb(data):
    _, _, length = struct.unpack_from("<4sII", data, 0)
    off, js, binc = 12, None, b""
    while off < length:
        clen, ctype = struct.unpack_from("<I4s", data, off)
        chunk = data[off + 8: off + 8 + clen]
        if ctype == b"JSON":
            js = json.loads(chunk)
        elif ctype == b"BIN\x00":
            binc = chunk
        off += 8 + clen
    return js, binc


def write_glb(js, binc):
    jb = json.dumps(js, separators=(",", ":")).encode()
    jb += b" " * ((4 - len(jb) % 4) % 4)
    binc += b"\x00" * ((4 - len(binc) % 4) % 4)
    total = 12 + 8 + len(jb) + 8 + len(binc)
    return (struct.pack("<4sII", b"glTF", 2, total) + struct.pack("<I4s", len(jb), b"JSON") + jb
            + struct.pack("<I4s", len(binc), b"BIN\x00") + binc)


def shrink(data, maxdim):
    js, binc = read_glb(data)
    views = js["bufferViews"]
    blobs = [binc[v.get("byteOffset", 0): v.get("byteOffset", 0) + v["byteLength"]] for v in views]
    for im in js.get("images", []):
        if "bufferView" not in im:
            continue
        i = im["bufferView"]
        img = Image.open(io.BytesIO(blobs[i]))
        img.load()
        if max(img.size) > maxdim:
            r = maxdim / max(img.size)
            img = img.resize((max(1, int(img.width * r)), max(1, int(img.height * r))), Image.LANCZOS)
        out = io.BytesIO()
        has_alpha = img.mode in ("RGBA", "LA") or (img.mode == "P" and "transparency" in img.info)
        if has_alpha:
            img.convert("RGBA").save(out, "PNG", optimize=True)
            im["mimeType"] = "image/png"
        else:
            img.convert("RGB").save(out, "JPEG", quality=85)
            im["mimeType"] = "image/jpeg"
        blobs[i] = out.getvalue()
    # repack all buffer views contiguously (4-byte aligned)
    newbin = bytearray()
    for v, b in zip(views, blobs):
        newbin += b"\x00" * ((4 - len(newbin) % 4) % 4)
        v["byteOffset"] = len(newbin)
        v["byteLength"] = len(b)
        newbin += b
    js["buffers"][0]["byteLength"] = len(newbin)
    return write_glb(js, bytes(newbin))


packed = {}
for (car, lod), maxdim in SHIP.items():
    raw = (SRC / f"{car}_{lod}.glb").read_bytes()
    small = shrink(raw, maxdim)
    (SRC / f"{car}_{lod}_ship.glb").write_bytes(small)
    packed.setdefault(car, {})[lod] = base64.b64encode(small).decode()
    print(f"{car}_{lod}: {len(raw)/1e6:.1f}MB -> {len(small)/1e6:.1f}MB")

js = "// Generated by tools/build_cars.py. See that file for model credits.\nwindow.ZENO_CARS=" + json.dumps(packed) + ";\n"
(ROOT / "assets/cars.js").write_text(js)
print(f"assets/cars.js {len(js)/1e6:.1f}MB")
