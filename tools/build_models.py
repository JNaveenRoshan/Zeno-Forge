"""Pack the chosen 3D car models into assets/models.js so index.html works when opened by double-click (no web server).

Run:  python tools/build_models.py
Source: Quaternius "Realistic Car Pack - Nov 2018" (CC0) unpacked into assets/raw/carpack.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OBJ_DIR = ROOT / "assets/raw/carpack/Realistic Car Pack - Nov 2018/OBJ"
CARS = {"ev": "NormalCar2", "ice": "NormalCar1", "suv": "SUV"}

out = {}
for key, name in CARS.items():
    out[key] = {
        "obj": (OBJ_DIR / f"{name}.obj").read_text(),
        "mtl": (OBJ_DIR / f"{name}.mtl").read_text(),
    }

js = "// Generated by tools/build_models.py from the CC0 Quaternius Realistic Car Pack.\nwindow.ZENO_MODELS=" + json.dumps({"cars": out}, separators=(",", ":")) + ";\n"
dest = ROOT / "assets/models.js"
dest.write_text(js)
print(f"wrote {dest} ({len(js)//1024} KB)")
